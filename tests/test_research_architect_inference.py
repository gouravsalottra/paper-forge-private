def test_text_corpus_keywords_infer_non_yfinance_evidence():
    """
    A study using earnings transcripts must not suggest 
    yfinance as the primary evidence route.
    """
    payload = {
        "topic": (
            "Using earnings call transcripts and NLP sentiment "
            "analysis to predict subsequent abnormal returns. "
            "Text corpus from quarterly earnings calls."
        )
    }
    result = _fallback_blueprint(payload)
    summary = result["blueprint_summary"]
    assert summary["evidence_source"] in {
        "text_corpus", "edgar_yfinance", "upload"
    }, (
        f"Text study should not suggest yfinance alone, "
        f"got {summary['evidence_source']}"
    )


def test_statistical_battery_covers_all_method_families():
    """Every method family must have at least 3 tests."""
    for method in VALID_METHOD_FAMILIES:
        battery = _statistical_battery(method)
        assert battery.get("tests"), (
            f"Empty test battery for: {method}"
        )
        assert len(battery["tests"]) >= 3, (
            f"Fewer than 3 tests for: {method}"
        )


def test_leakage_policy_covers_all_method_families():
    """Every method family must have a leakage rule."""
    for method in VALID_METHOD_FAMILIES:
        policy = _leakage_policy(method)
        assert policy.get("primary_rule"), (
            f"Missing leakage rule for: {method}"
        )


def test_economic_significance_covers_all_method_families():
    """Every method family must have an economic significance rule."""
    for method in VALID_METHOD_FAMILIES:
        sig = _economic_significance(method)
        assert sig.get("rule"), (
            f"Missing economic significance for: {method}"
        )


def test_reviewer_gate_method_focus_covers_all_families():
    """Every method family must have at least 3 reviewer dimensions."""
    for method in VALID_METHOD_FAMILIES:
        gate = _reviewer_gate(False, method)
        focus = gate.get("method_focus", [])
        assert isinstance(focus, list) and len(focus) >= 3, (
            f"Insufficient reviewer focus for: {method}"
        )
