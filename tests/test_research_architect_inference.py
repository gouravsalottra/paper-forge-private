def test_directional_comparative_hypothesis_is_confirmatory():
    """
    Any brief containing a directional comparison between 
    conditions must be classified as confirmatory.
    Uses abstract placeholder language, not a real topic.
    """
    payload = {
        "topic": (
            "Does condition A produce outcome X at a higher "
            "rate than condition B when controlling for Z? "
            "This study compares two market regimes to test "
            "whether regime A amplifies outcome X relative "
            "to regime B."
        )
    }
    result = _fallback_blueprint(payload)
    summary = result["blueprint_summary"]
    # Directional comparative question must not be exploratory
    assert summary["research_stance"] in {
        "confirmatory", "confirmatory_pap"
    } or summary["method_style"] != "descriptive", (
        "Directional comparative hypothesis must not be "
        "classified as exploratory descriptive"
    )


def test_synthetic_data_study_does_not_infer_yfinance():
    """
    A study that generates its own data must not suggest 
    yfinance as the evidence route.
    Uses abstract placeholder language.
    """
    payload = {
        "topic": (
            "This study uses a synthetic market environment "
            "where agents interact according to learned "
            "strategies. The data is generated by the "
            "simulation, not sourced from external providers."
        )
    }
    result = _fallback_blueprint(payload)
    summary = result["blueprint_summary"]
    assert summary["evidence_source"] != "yfinance", (
        "Simulation study must not infer yfinance as evidence"
    )


